import { chromium } from 'playwright-core'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const output = new URL('./artifacts/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu', '--enable-features=Vulkan', '--use-angle=metal', '--ignore-gpu-blocklist'] })
const reports = []
try {
  for (const phone of [false, true]) {
    const device = phone ? 'phone' : 'desktop'
    const context = await browser.newContext({ viewport: phone ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, hasTouch: phone, isMobile: phone, permissions: ['clipboard-read', 'clipboard-write'] })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
    await page.goto(`http://127.0.0.1:5187/?room=ui-${device}-${Date.now()}`)
    await page.waitForFunction(() => window.syn3h?.game.tick > 25, null, { timeout: 60000 })
    await page.evaluate(() => document.fonts.ready)
    await page.waitForTimeout(3000)
    const shot = name => page.screenshot({ path: new URL(`${device}-${name}.png`, output).pathname })
    const panel = async id => {
      await page.evaluate(id => syn3h.shell.showPanel(id), id)
      await page.waitForFunction(id => document.querySelector('.lobby-panels').dataset.activePanel === id && document.querySelector('.lobby-panels').dataset.busy === 'false', id)
    }
    assert.equal(await page.evaluate(() => syn3h.audio.track), 'SpaceStation')
    await shot('index')
    await page.locator('[data-panel=index] [data-goto=vehicle]').click()
    await page.waitForFunction(() => document.querySelector('.lobby-panels').dataset.activePanel === 'vehicle')
    await page.waitForFunction(() => document.querySelector('.shell-vehicle-preview').dataset.ready === 'true', null, { timeout: 30000 })
    await page.locator('[name=vehicle][value=buggy-classic]').check()
    await page.waitForFunction(() => document.querySelector('.shell-vehicle-preview').dataset.ready === 'true')
    await shot('vehicle-classic')
    await page.locator('[name=vehicle][value=buggy-syn3h]').check()
    await page.waitForFunction(() => document.querySelector('.shell-vehicle-preview').dataset.ready === 'true')
    await page.locator('[name=bodyColor]').fill('#ee7722'); await page.locator('[name=accentColor]').fill('#33aaff')
    await page.waitForTimeout(500)
    assert.deepEqual(await page.evaluate(() => ({ kind: syn3h.shell.vehicleKind, body: syn3h.shell.bodyColor, accent: syn3h.shell.accentColor })), { kind: 'buggy-syn3h', body: '#ee7722', accent: '#33aaff' })
    await shot('vehicle-syn3h')
    for (const kind of ['jet', 'hovercraft']) {
      await page.locator(`[name=vehicle][value=${kind}]`).check()
      await page.waitForFunction(() => document.querySelector('.shell-vehicle-preview').dataset.ready === 'true')
      await shot(`vehicle-${kind}`)
      await page.locator('.vehicle-help').scrollIntoViewIfNeeded(); await shot(`help-${kind}`)
    }
    await page.locator('[name=vehicle][value=buggy-syn3h]').check()
    await panel('explore')
    await page.locator('#shell-name').fill('UI Explorer')
    await page.locator('[data-panel=explore] .shell-invite').click()
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /room=ui-/)
    await shot('explore')
    await panel('music')
    await page.locator('#shell-track').selectOption('SpaceStation')
    await page.locator('#music-volume').fill('0.23')
    assert.ok(Math.abs(await page.evaluate(() => syn3h.params.get('audio.music').value) - 0.23) < 1e-6)
    await page.locator('.shell-mute').click()
    assert.equal(await page.evaluate(() => syn3h.audio.isMuted), true)
    await page.locator('.shell-mute').click()
    await page.waitForFunction(() => syn3h.audio.state === 'running' && syn3h.audio.loadedSounds === 4)
    await shot('music')
    await panel('worlds')
    await page.locator('[data-sky="Violet dusk"]').click()
    assert.equal(await page.evaluate(() => syn3h.params.get('sun.timeOfDay').value), 17.4)
    await page.locator('#sky-time').fill('12.5')
    await page.locator('#world-seed').fill('77'); await page.locator('#new-world').click()
    assert.equal(await page.evaluate(() => syn3h.params.get('world.seed').value), 77)
    await page.evaluate(async () => { const { defineParam, params } = await import('/shared/params.ts'); if (!params.get('bots.count')) defineParam({ id: 'bots.count', label: 'Bots', group: 'Bots', scope: 'world', default: 0, min: 0, max: 8, step: 1 }) })
    await page.waitForFunction(() => !document.querySelector('.bots-control').hidden)
    await page.locator('#bots-count').fill('3')
    assert.equal(await page.evaluate(() => syn3h.params.get('bots.count').value), 3)
    await shot('worlds')
    await page.locator('[data-panel=worlds] .panel-back').scrollIntoViewIfNeeded()
    await shot('worlds-bottom')
    await panel('settings'); await shot('settings')
    await panel('advanced')
    assert.equal(await page.locator('.syn3h-advanced').isVisible(), true)
    await shot('advanced')
    await page.locator('.syn3h-advanced').getByText('Audio', { exact: true }).click()
    await page.waitForTimeout(500)
    await shot('advanced-audio')
    await panel('about'); await shot('about')
    const scores = ['net: room demo   ping 12 ms   delay 20 ms', 'host: you   shared sliders open to all', '> UI Explorer    12  [IT] (you) (host)', '  Guest            3  ', 'Guest joined']
    await page.evaluate(lines => syn3h.shell.setStatus(lines), scores)
    await panel('multiplayer'); await shot('multiplayer')
    assert.equal(await page.locator('.shell-scoreboard .is-it.is-self').count(), 1)
    await page.evaluate(() => { window.syn3hNet = { isHost: false, locked: true, canEditWorld: false, setLocked() {} } })
    await panel('worlds')
    assert.equal(await page.locator('#new-world').isDisabled(), true)
    assert.equal(await page.locator('#sky-time').isDisabled(), true)
    await shot('worlds-locked')
    await panel('settings')
    assert.match(await page.locator('.host-note').textContent(), /locked by host/)
    await shot('settings-locked')
    await page.evaluate(() => { window.syn3hNet = { isHost: true, locked: false, canEditWorld: true, setLocked(value) { this.locked = value; window.lockCalled = value } } })
    await page.waitForFunction(() => !document.querySelector('.host-lock').hidden)
    await page.locator('#host-lock').check()
    assert.equal(await page.evaluate(() => window.lockCalled), true)
    await shot('settings-host')
    await page.evaluate(() => { delete window.syn3hNet })
    await panel('explore'); await page.locator('.shell-play').click()
    await page.waitForFunction(() => syn3h.shell.playing && !syn3h.shell.menuOpen)
    assert.equal(await page.evaluate(() => syn3h.game.input.suspended), false)
    await page.waitForFunction(() => window.syn3hNet?.connected === true)
    await page.evaluate(lines => syn3h.shell.setStatus(lines), scores)
    await shot('hud')
    if (phone) {
      assert.equal(await page.locator('.touch-controls').isVisible(), true)
      const stick = await page.locator('.touch-stick').boundingBox(), fire = await page.locator('[data-action=fire]').boundingBox()
      const cdp = await context.newCDPSession(page)
      const drive = { x: stick.x + stick.width / 2, y: stick.y + 12, id: 1 }, shoot = { x: fire.x + 30, y: fire.y + 30, id: 2 }
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [drive] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [drive, shoot] })
      await page.waitForFunction(() => syn3h.game.input.state.y > 0.8 && syn3h.game.input.state.fire)
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
      await page.waitForFunction(() => !syn3h.game.input.state.fire && syn3h.game.input.state.y === 0)
    }
    await page.locator('.shell-menu-button').click()
    await page.waitForFunction(() => syn3h.shell.menuOpen)
    assert.equal(await page.evaluate(() => syn3h.game.input.suspended), true)
    assert.equal(await page.locator('.touch-controls').isVisible(), false)
    await page.waitForFunction(() => document.querySelector('.lobby-panels').dataset.activePanel === 'index')
    await shot('menu')
    await page.keyboard.press('Escape')
    assert.equal(await page.evaluate(() => syn3h.shell.menuOpen), false)
    assert.equal(await page.evaluate(() => localStorage.getItem('syn3h.playerName')), 'UI Explorer')
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('syn3h.vehicle')).vehicleKind), 'buggy-syn3h')
    assert.deepEqual(await page.evaluate(() => syn3h.audio.errors), [])
    assert.deepEqual(errors, [])
    reports.push({ device, panels: 9, audio: await page.evaluate(() => ({ state: syn3h.audio.state, track: syn3h.audio.track, buffers: syn3h.audio.loadedSounds })), errors })
    await context.close()
  }
  await writeFile(new URL('report.json', output), JSON.stringify(reports, null, 2)); console.log(JSON.stringify(reports, null, 2))
} finally { await browser.close() }
