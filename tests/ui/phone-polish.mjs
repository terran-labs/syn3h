import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu', '--use-angle=metal', '--ignore-gpu-blocklist'] })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await page.goto('http://127.0.0.1:5187/?room=ui-polish')
  await page.waitForFunction(() => window.syn3h?.game.tick > 25)
  await page.waitForTimeout(3000)
  await page.screenshot({ path: 'tests/ui/artifacts/phone-index-final.png' })
  await page.locator('[data-panel=index] [data-goto=vehicle]').tap()
  await page.waitForFunction(() => document.querySelector('.shell-vehicle-preview').dataset.ready === 'true')
  await page.waitForFunction(() => document.querySelector('.lobby-panels').dataset.busy === 'false')
  await page.screenshot({ path: 'tests/ui/artifacts/phone-vehicle-final.png' })
  await page.evaluate(() => syn3h.shell.play())
  await page.waitForFunction(() => window.syn3hNet?.connected)
  await page.waitForTimeout(500)
  const nav = await page.locator('.hud-navigation').boundingBox(), toast = await page.locator('.shell-toast').boundingBox(), stick = await page.locator('.touch-stick-hint').evaluate(el => el.getBoundingClientRect())
  assert.ok(toast.y > nav.y + nav.height)
  assert.ok(toast.y + toast.height < stick.y)
  await page.screenshot({ path: 'tests/ui/artifacts/phone-hud-final.png' })
  await page.locator('.shell-menu-button').tap()
  await page.waitForFunction(() => document.querySelector('.lobby-panels').dataset.activePanel === 'index')
  assert.equal(await page.locator('.shell-toast').isVisible(), false)
  assert.equal(await page.locator('.touch-controls').isVisible(), false)
  await page.screenshot({ path: 'tests/ui/artifacts/phone-menu-final.png' })
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(() => syn3h.shell.menuOpen), false)
  assert.deepEqual(errors, [])
  console.log('Phone notifications, menu, preview and touch layout passed')
} finally { await browser.close() }
