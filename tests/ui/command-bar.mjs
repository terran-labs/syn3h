import { chromium, webkit, devices } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const out = 'tests/ui/artifacts/command-bar'
await mkdir(out, { recursive: true })
for (const mode of ['desktop', 'phone', 'landscape']) {
 const touch = mode !== 'desktop', browser = await (touch ? webkit.launch() : chromium.launch({ channel: 'chrome', headless: true }))
 try {
  const page = await browser.newPage(touch ? devices[mode === 'phone' ? 'iPhone 14' : 'iPhone 14 landscape'] : { viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.SYN3H_URL}?autoplay=1&room=command-${mode}-${Date.now()}`)
  await page.waitForFunction(() => window.syn3h?.game.tick > 30, null, { timeout: 120000 })
  await page.locator('.boot-veil').waitFor({ state: 'hidden' })
  const rail = page.locator('.world-inspector')
  if (touch && !await rail.isVisible()) await page.locator('.inspector-toggle').tap()
  else if (await page.evaluate(() => !!document.pointerLockElement)) await page.keyboard.press('Escape')
  await rail.waitFor({ state: 'visible' })
  await page.waitForFunction(() => !document.querySelector('.world-inspector').getAnimations().some(a => a.playState === 'running'))
  const bar = rail.locator('.rail-command'), search = bar.locator('.wi-search')
  assert.equal(await rail.locator('.rail-foot, .rail-world, .rail-close').count(), 0)
  assert.ok(await bar.evaluate(el => el.nextElementSibling.classList.contains('wi-cards')))
  const before = await rail.locator('.wi-card').evaluateAll(es => es.map(el => el.classList.contains('is-open')))
  await page.screenshot({ path: `${out}/${mode}-clear.png` })
  await search.fill('day length')
  assert.equal(await bar.locator('.wi-search-count').innerText(), '1 setting')
  assert.ok(await rail.locator('[data-id="sun.dayLength"] mark').count() > 0)
  assert.match(await bar.locator('.wi-search-strip').innerText(), /day length/)
  const row = rail.locator('[data-id="sun.dayLength"]'), slider = row.locator('input[type=range]')
  await slider.scrollIntoViewIfNeeded(); await slider.focus(); await page.keyboard.press('Home')
  assert.equal(await row.locator('.wi-num').innerText(), 'Off')
  await page.keyboard.press('ArrowRight'); assert.equal(await row.locator('.wi-num').innerText(), '10 s')
  await row.locator('.wi-num').click(); const exact = row.locator('.wi-num-edit'); await exact.fill('351'); await exact.press('Enter')
  assert.equal(await row.locator('.wi-num').innerText(), '5 min 51 s')
  await page.screenshot({ path: `${out}/${mode}-search.png` })
  await search.focus(); await page.keyboard.press('Escape')
  assert.equal(await search.inputValue(), '')
  assert.deepEqual(await rail.locator('.wi-card').evaluateAll(es => es.map(el => el.classList.contains('is-open'))), before)
  assert.equal(await page.evaluate(() => syn3h.game.input.suspended), false)
  await search.fill('no-such-setting-xyz'); assert.equal(await bar.locator('.wi-search-count').innerText(), 'No matches')
  await bar.getByRole('button', { name: 'Clear search' }).click()
  await search.blur(); await page.keyboard.press('Control+f'); assert.ok(await search.evaluate(el => el === document.activeElement))
  await search.blur(); await page.evaluate(() => document.activeElement?.blur()); await page.keyboard.type('gravity'); assert.equal(await search.inputValue(), 'gravity')
  await bar.getByRole('button', { name: 'Clear search' }).click()
  const bounds = await bar.boundingBox(); assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= page.viewportSize().height)
  for (const button of await bar.locator('.wi-actions button').all()) assert.ok((await button.boundingBox()).height >= 44)
  await bar.getByRole('button', { name: 'Pause', exact: true }).click(); await page.waitForFunction(() => syn3h.game.input.suspended)
  assert.equal(await bar.locator('.rail-pause').innerText(), 'Resume')
  await page.locator('.pause-veil').click(); await page.waitForFunction(() => !syn3h.game.input.suspended)
  assert.deepEqual(errors, []); console.log(JSON.stringify({ mode, errors, passed: true }))
 } finally { await browser.close() }
}
